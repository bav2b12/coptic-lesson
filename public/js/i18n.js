class I18n {
  constructor() {
    this.lang = localStorage.getItem('doros_coptic_lang') || 'ar';
    this.updateDOMDirection();
  }

  t(key) {
    return (translations[this.lang] && translations[this.lang][key]) || 
           (translations['ar'] && translations['ar'][key]) || 
           key;
  }

  getLang() {
    return this.lang;
  }

  setLang(newLang) {
    if (newLang !== 'ar' && newLang !== 'en') return;
    this.lang = newLang;
    localStorage.setItem('doros_coptic_lang', newLang);
    this.updateDOMDirection();
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: newLang } }));
  }

  toggleLang() {
    this.setLang(this.lang === 'ar' ? 'en' : 'ar');
  }

  updateDOMDirection() {
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.lang === 'ar' ? 'rtl' : 'ltr';
    document.body.dir = this.lang === 'ar' ? 'rtl' : 'ltr';
  }
}

window.i18n = new I18n();
